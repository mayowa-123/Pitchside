// PitchSide AI: the per-video "tactical insight" popup (openAiInsight/
// closeAiInsight) and the Groq-powered chat assistant (sendAiMessage and
// its supporting UI). Split out of app.js (~12KB) so this only downloads
// for users who actually open an insight popup or the AI tab.
//
// LOADED VIA DYNAMIC import() FROM app.js — app.js stays a classic
// script (see match-detail.js's header comment for the full reasoning).
//
// UNLIKE war-room.js: every entry point here is reachable from STATIC
// onclick/onchange attributes already sitting in index.html (the AI tab
// under "More", and every video card's insight button) — not HTML this
// module generates itself. That means openAiInsight, closeAiInsight,
// sendAiMessage, aiTriggerFile, aiToggleAttachMenu, and
// aiHandleFileSelect all need PERMANENT STUBS in app.js (the
// match-detail.js pattern: exist synchronously from page load, delegate
// to this module once loaded) — direct window assignment from within
// this module (the war-room.js pattern) would be too late for these,
// since they can be clicked before this module has ever loaded.
// aiRemoveAttach is the one exception: it's only ever generated by this
// module's own renderAttachPreview, so by the time it could be clicked,
// this module is already loaded — direct assignment at the bottom of
// this file is fine for that one.
//
// escapeAttr (used to build the insight button's onclick string) is
// NOT moved here — it's shared with Post Creator's match-tagging
// elsewhere in app.js, and stays there as a plain function declaration

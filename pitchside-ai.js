export function aiTriggerFile(accept, type) {
  const inp = document.getElementById('ai-file-input');
  inp.accept = accept;
  inp.dataset.fileType = type;
  inp.value = '';
  inp.click();
  document.getElementById('ai-attach-menu').classList.remove('open');
}

export function aiHandleFileSelect(input) {
  const file = input.files[0];
  if (!file) return;
  const type = input.dataset.fileType || 'file';
  const reader = new FileReader();
  reader.onload = function(e) {
    const dataUrl = e.target.result;
    aiPendingAttachments.push({ type, dataUrl, mimeType: file.type, name: file.name });
    renderAttachPreview();
  };
  reader.readAsDataURL(file);
}

export function renderAttachPreview() {
  const strip = document.getElementById('ai-attach-preview');
  strip.innerHTML = '';
  if (aiPendingAttachments.length === 0) {
    strip.classList.remove('has-items');
    return;
  }
  strip.classList.add('has-items');
  aiPendingAttachments.forEach((a, i) => {
    const thumb = document.createElement('div');
    thumb.className = 'ai-attach-thumb';
    if (a.type === 'photo') {
      thumb.innerHTML = `<img src="${a.dataUrl}" alt="">`;
    } else if (a.type === 'video') {
      thumb.innerHTML = `<video src="${a.dataUrl}"></video>`;
    } else {
      thumb.innerHTML = `<div class="ai-attach-type"><svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2"><path d="M14 2H6a2 2 0 0 0-2 2v16a2 2 0 0 0 2 2h12a2 2 0 0 0 2-2V8z"/><polyline points="14 2 14 8 20 8"/></svg><span>${escHtml(a.name.split('.').pop().toUpperCase())}</span></div>`;
    }
    thumb.innerHTML += `<div class="ai-attach-remove" onclick="aiRemoveAttach(${i})">✕</div>`;
    strip.appendChild(thumb);
  });
}

export function aiRemoveAttach(i) {
  aiPendingAttachments.splice(i, 1);
  renderAttachPreview();
}

export let _aiRequestInFlight = false;

export async function sendAiMessage(presetText) {
  if (_aiRequestInFlight) {
    if (typeof showToast === 'function') showToast('⏳ Still waiting on the previous reply — one sec');
    return;
  }

  const input = document.getElementById('ai-input');
  const text  = (presetText || input.value).trim();
  const attachments = [...aiPendingAttachments];

  if (!text && attachments.length === 0) return;
  input.value = '';
  aiPendingAttachments = [];
  renderAttachPreview();

  // Remove welcome cards and chips
  const cards = document.getElementById('ai-welcome-cards');
  if (cards) cards.remove();
  const chips = document.getElementById('ai-chips');
  if (chips) chips.remove();

  const displayText = text || (attachments.length > 0 ? `[Sent ${attachments.length} file${attachments.length>1?'s':''}]` : '');
  appendAiMessage('user', displayText, attachments);

  // Build message content for API
  const userContent = [];

  // Add images to content
  attachments.forEach(a => {
    if (a.type === 'photo' && a.mimeType.startsWith('image/')) {
      const base64 = a.dataUrl.split(',')[1];
      userContent.push({
        type: 'image',
        source: { type: 'base64', media_type: a.mimeType, data: base64 }
      });
    }
  });

  if (text) {
    userContent.push({ type: 'text', text });
  } else if (attachments.length > 0) {
    const hasImage = attachments.some(a => a.type === 'photo');
    const hasVideo = attachments.some(a => a.type === 'video');
    const prompt = hasImage ? 'Analyze this football image and tell me everything you observe.' : hasVideo ? 'I sent a football video. Describe what kind of football content this likely is and give relevant analysis.' : 'Analyze the attached file in the context of football.';
    userContent.push({ type: 'text', text: prompt });
  }

  aiMessages.push({ role: 'user', content: userContent.length === 1 && userContent[0].type === 'text' ? userContent[0].text : userContent });
  showAiTyping();
  _aiRequestInFlight = true;

  try {
    const res = await fetch('/api/ai', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        max_tokens: 800,
        system: AI_SYSTEM_PROMPT,
        messages: aiMessages,
      })
    });

    const data = await res.json();
    hideAiTyping();

    if (data.content && data.content[0] && data.content[0].text) {
      const reply = data.content[0].text;
      appendAiMessage('bot', reply);
      aiMessages.push({ role: 'assistant', content: reply });

      // Keep history short — resending the WHOLE conversation on every
      // message was the actual cause of "Request Entity Too Large" and
      // rate-limit errors after just a couple of messages. 10 messages
      // (~5 exchanges) is plenty of context without ballooning token count.
      if (aiMessages.length > 10) aiMessages = aiMessages.slice(-10);

      // Strip image data from older messages in history — only the message
      // it was actually sent with needs the real image bytes; carrying full
      // base64 images forward in every subsequent request is what made
      // token/size usage explode fastest of anything in the history.
      aiMessages = aiMessages.map((m, i) => {
        if (i === aiMessages.length - 1) return m; // leave the most recent message untouched
        if (Array.isArray(m.content)) {
          return { ...m, content: m.content.filter(c => c.type !== 'image').map(c => c.type === 'text' ? c : { type: 'text', text: '[image sent earlier]' }) };
        }
        return m;
      });
    } else if (data.error) {
      const errMsg = data.error.message || 'Something went wrong.';
      const friendly = errMsg.includes('x-api-key') || errMsg.includes('api-key') || errMsg.includes('API key') || errMsg.includes('Invalid API Key')
        ? '⚠️ AI service is currently unavailable. The app owner needs to check the Groq API key.'
        : `⚠️ ${errMsg}`;
      appendAiMessage('bot', friendly);
      // A failed request still added a 'user' message to aiMessages above —
      // remove it so the next real request doesn't send two user turns in a
      // row (which is what was corrupting message order and causing more
      // failures downstream).
      if (aiMessages.length && aiMessages[aiMessages.length - 1].role === 'user') aiMessages.pop();
    } else {
      appendAiMessage('bot', "Hmm, I didn't get a response. Please try again! ⚽");
      if (aiMessages.length && aiMessages[aiMessages.length - 1].role === 'user') aiMessages.pop();
    }
  } catch(e) {
    hideAiTyping();
    appendAiMessage('bot', "⚠️ Couldn't connect to AI. Check your connection and try again.");
    if (aiMessages.length && aiMessages[aiMessages.length - 1].role === 'user') aiMessages.pop();
  } finally {
    _aiRequestInFlight = false;
  }
}

